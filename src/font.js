// Each glyph as a list of [x, y, w] horizontal runs, so a letter is a handful
// of fillRects instead of up to 35. Rows beyond seven sit above the cell.
const RUNS = {};
for (const [ch, rows] of Object.entries(GLYPHS)) {
  const runs = [];
  const top = 7 - rows.length;
  rows.forEach((row, ry) => {
    const y = ry + top;
    let x = 0;
    while (x < 5) {
      if (row[x] !== '#') { x++; continue; }
      let e = x;
      while (e < 5 && row[e] === '#') e++;
      runs.push([x, y, e - x]);
      x = e;
    }
  });
  RUNS[ch] = runs;
}

const fold = (s) => [...s].map((c) => (GLYPHS[c] || GLYPHS[c.toUpperCase()]
  ? c : c.normalize('NFD').replace(/[̀-ͯ]/g, ''))).join('');

export function textWidth(text, scale = 1) {
  return fold(text).length * 6 * scale - scale;
}

// align: 'left' | 'center' | 'right'. A shadow is drawn one pixel down-right.
export function drawText(ctx, text, x, y, { color = '#fff', scale = 1, align = 'left', shadow = '#000' } = {}) {
  const s = fold(text);
  let cx = Math.round(x - (align === 'center' ? textWidth(s, scale) / 2 : align === 'right' ? textWidth(s, scale) : 0));
  const cy = Math.round(y);
  const pass = (col, ox, oy) => {
    ctx.fillStyle = col;
    let px = cx;
    for (const raw of s) {
      const runs = RUNS[raw] || RUNS[raw.toUpperCase()] || RUNS['?'];
      for (const [rx, ry, rw] of runs) ctx.fillRect(px + rx * scale + ox, cy + ry * scale + oy, rw * scale, scale);
      px += 6 * scale;
    }
  };
  if (shadow) pass(shadow, scale, scale);
  pass(color, 0, 0);
}

// Splits `text` into lines no wider than `maxWidth` pixels, breaking at
// spaces; a word longer than a line gets a line of its own. "\n" forces a
// break.
export function wrapText(text, maxWidth, scale = 1) {
  const lines = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ').filter(Boolean)) {
      const next = line ? `${line} ${word}` : word;
      if (line && textWidth(next, scale) > maxWidth) {
        lines.push(line);
        line = word;
      } else {
        line = next;
      }
    }
    lines.push(line);
  }
  return lines;
}
